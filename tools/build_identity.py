#!/usr/bin/env python3
"""Generate a non-secret, reproducible KeyValet firmware build identity."""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


def git_output(project_root: Path, *arguments: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(project_root), *arguments],
        check=True,
        stdout=subprocess.PIPE,
    ).stdout


def build_prefix(project_root: Path, variant: str) -> str:
    revision = git_output(project_root, "rev-parse", "HEAD").decode().strip()
    short_revision = revision[:12]
    status = git_output(
        project_root, "status", "--porcelain=v1", "--untracked-files=all"
    )
    state = "dirty" if status else "clean"

    return f"{short_revision}-{state}-{variant}"


def render_header(prefix: str, variant: str) -> str:
    return (
        "#pragma once\n\n"
        "// Generated by tools/build_identity.py; do not edit.\n"
        f'#define KEYVALET_BUILD_PREFIX "{prefix}"\n'
        f'#define KEYVALET_BUILD_VARIANT "{variant}"\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, required=True)
    parser.add_argument("--variant", choices=("production", "diagnostic"), required=True)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()

    project_root = arguments.project_root.resolve()
    prefix = build_prefix(project_root, arguments.variant)
    content = render_header(prefix, arguments.variant)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    if not arguments.output.exists() or arguments.output.read_text() != content:
        arguments.output.write_text(content)
    print(prefix)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
